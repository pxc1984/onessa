#[test]
fn uncaught_runtime_error_reports_line() {
    let (output, err) = run("Сообщить(1);\nСообщить(\"а\" < 1);").unwrap_err();
    assert_eq!(output, "1\n");
    assert!(
        err.starts_with("test.bsl:2: Сравнение на больше/меньше"),
        "{err}"
    );
}

