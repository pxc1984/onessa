#[test]
fn control_flow() {
    let source = "
        Для Сч = 1 По 10 Цикл
            Если Сч % 2 = 0 Тогда
                Продолжить;
            ИначеЕсли Сч > 7 Тогда
                Прервать;
            КонецЕсли;
            Сообщить(Сч);
        КонецЦикла;
        Н = 3;
        Пока Н > 0 Цикл
            Сообщить(\"Н=\" + Н);
            Н = Н - 1;
        КонецЦикла;
        Сообщить(?(Н = 0, \"ноль\", \"не ноль\"));";
    assert_eq!(
        lines(source),
        ["1", "3", "5", "7", "Н=3", "Н=2", "Н=1", "ноль"]
    );
}

