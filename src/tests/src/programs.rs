use crate::{compile, run};

/// Output lines of a successful run.
fn lines(source: &str) -> Vec<String> {
    match run(source) {
        Ok(output) => output.lines().map(str::to_string).collect(),
        Err((output, err)) => panic!("uncaught exception: {err}\noutput:\n{output}"),
    }
}

#[test]
fn hello_world() {
    assert_eq!(lines("Сообщить(\"Привет, мир!\");"), ["Привет, мир!"]);
    assert_eq!(lines("Message(\"Hello\")"), ["Hello"]);
}

#[test]
fn arithmetic_and_precedence() {
    assert_eq!(
        lines(
            "Сообщить(1 + 2 * 3);
             Сообщить((1 + 2) * 3);
             Сообщить(10 - 4 - 3);
             Сообщить(7 / 2);
             Сообщить(7 % 3);
             Сообщить(-2 * -3);
             Сообщить(0.1 + 0.2);
             Сообщить(1000000);"
        ),
        ["7", "9", "3", "3,5", "1", "6", "0,3", "1\u{a0}000\u{a0}000"]
    );
}

